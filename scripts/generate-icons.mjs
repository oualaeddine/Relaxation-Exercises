// Generates src/ui/icons.generated.ts from @material-symbols/svg-400 (outlined, weight 400).
// Only the icons listed below are bundled. Run `npm run icons` after editing the list.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = dirname(require.resolve('@material-symbols/svg-400/package.json'));
const here = dirname(fileURLToPath(import.meta.url));

const ICONS = `
accessibility_new add adjust air arrow_back arrow_downward arrow_forward arrow_upward kid_star balance bar_chart bed
bedtime bolt bookmark_add calendar_month chair check check_circle chevron_left chevron_right circle close cloud compress
contrast counter_5 crop_square delete directions_walk do_not_disturb_on done_all download eco edit_note error keyboard_arrow_down
explore favorite fast_forward filter_drama filter_list filter_vintage fitness_center flag flare footprint front_hand
graphic_eq grid_view headphones health_and_safety healing hearing history home info show_chart keyboard lightbulb lock mood
music_note nature nature_people nordic_walking north notifications_active pan_tool pan_tool_alt park pause pause_circle
person play_arrow privacy_tip psychology remove repeat replay restart_alt schedule search self_improvement
sentiment_satisfied settings shield skip_next skip_previous south spa stop_circle sync_alt timelapse timer touch_app tune
upload verified verified_user mobile_vibrate visibility volume_off volume_up warning water_drop waves record_voice_over
checklist question_mark trending_up
`.trim().split(/\s+/);

const filled = new Set(['air', 'spa', 'check_circle', 'pause', 'play_arrow', 'favorite', 'pause_circle', 'volume_up', 'mobile_vibrate', 'eco', 'filter_vintage', 'health_and_safety']);

function pathsOf(file) {
  const svg = readFileSync(file, 'utf8');
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`No path in ${file}`);
  return paths.join(' ');
}

const entries = [];
for (const name of [...new Set(ICONS)].sort()) {
  const outline = pathsOf(join(root, 'outlined', `${name}.svg`));
  let fill = null;
  if (filled.has(name)) fill = pathsOf(join(root, 'outlined', `${name}-fill.svg`));
  entries.push(`  ${name}: { d: ${JSON.stringify(outline)}${fill ? `, fill: ${JSON.stringify(fill)}` : ''} },`);
}

writeFileSync(
  join(here, '..', 'src', 'ui', 'icons.generated.ts'),
  `// Generated by scripts/generate-icons.mjs from @material-symbols/svg-400 (Apache-2.0). Do not edit.\n` +
    `export const ICONS = {\n${entries.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`Generated ${entries.length} icons.`);
